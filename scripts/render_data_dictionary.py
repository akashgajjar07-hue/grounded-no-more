"""Render the data dictionary and the assumption register to Markdown.

Sources of truth:
  * src/gnm/schemas.py        -> data/data_dictionary.md
  * config/assumptions.yaml   -> docs/assumption_register.md  (via gnm.config.assumption_register)

Both outputs are GENERATED. Edit the sources, then re-run:

    python scripts/render_data_dictionary.py
"""
from __future__ import annotations

import json
from pathlib import Path

from gnm import schemas
from gnm.config import ROOT, assumption_register

DICT_OUT = ROOT / "data" / "data_dictionary.md"
REG_OUT = ROOT / "docs" / "assumption_register.md"

# v2.1 release labels: the locked config keeps its archetype strings (V21-0); rendered text uses generic names.
RELABEL = [("Legacy OEM-quote", "Starting-point OEM-quote"), ("legacy OEM-quote", "starting-point OEM-quote"),
           ("legacy line-station", "starting-point line-station"), ("legacy provisioning", "starting-point provisioning"),
           ("A320-family archetype", "narrowbody archetype"), ("787-family archetype", "widebody archetype"),
           ("A320-family", "narrowbody"), ("787-family", "widebody"), ("787 LRUs", "widebody LRUs")]


def relabel(text: str) -> str:
    """Relabel locked archetype strings for display (whole-token replacements only)."""
    import re
    for a, b in RELABEL:
        text = re.sub(rf"(?<![\w-]){re.escape(a)}(?![\w])", b, text)
    return text


HEADER = "<!-- GENERATED by scripts/render_data_dictionary.py from {src}. Do not edit by hand. -->\n\n"


def _esc(text) -> str:
    """Escape a value for a Markdown table cell."""
    if text is None:
        return ""
    return str(text).replace("|", "\\|").replace("\n", " ")


def _anchor(name: str) -> str:
    return name.lower().replace("_", "_")


def render_dictionary() -> str:
    tables = schemas.TABLES
    public = [t for t in tables.values() if not t.hidden]
    hidden = [t for t in tables.values() if t.hidden]

    out = [HEADER.format(src="src/gnm/schemas.py"), "# Data dictionary\n\n"]
    out.append(
        "Every table written to `data/processed/` (Parquet, plus DuckDB views) is defined in "
        "[`src/gnm/schemas.py`](../src/gnm/schemas.py) and checked by `validate_table()`. "
        "All data describe **Falcon Hub Airways (fictional)**. Nothing here is operator data or "
        "measured aviation reliability.\n\n"
    )
    out.append("## Conventions\n\n")
    out.append("| Item | Rule |\n|---|---|\n")
    out.append("| Time | Integer `*_h` columns are hours since the simulated epoch `2023-01-02T00:00Z` (UTC). `week = h // 168`. |\n")
    out.append("| Money | AED, float64, columns end in `_aed`. Capital is never added to annual operating cost. |\n")
    out.append("| Quantities | int64, never negative, except the signed `inventory_transactions.qty_delta`. |\n")
    out.append("| Provenance | Each table carries one tag: `REAL`, `DERIVED`, `ASSUMED` or `SIMULATED`. |\n")
    out.append("| Hidden tables | Tables marked *hidden* hold generator ground truth. They live in `data/ground_truth/` and only `gnm.eval.truth_recovery` may read them. |\n\n")

    out.append("## Enumerations\n\n")
    out.append("| Enum | Values |\n|---|---|\n")
    for enum in (schemas.Provenance, schemas.PartClass, schemas.DeadlineClass, schemas.SerialState,
                 schemas.Archetype, schemas.DemandClass, schemas.RequestSource, schemas.TxnType):
        vals = ", ".join(f"`{e.value}`" for e in enum)
        out.append(f"| `{enum.__name__}` | {vals} |\n")
    out.append(
        "\nDeadline classes `D0`/`D3`/`D10` are **hypothetical requirement deadlines** "
        f"({', '.join(f'{k} = {v} h' for k, v in schemas.DEADLINE_HOURS.items())}). They are not MEL categories.\n\n"
    )

    out.append("## Tables\n\n| Table | Provenance | Rows describe |\n|---|---|---|\n")
    for t in public:
        out.append(f"| [`{t.name}`](#{_anchor(t.name)}) | `{t.provenance.value}` | {_esc(t.desc)} |\n")
    for t in hidden:
        out.append(f"| [`{t.name}`](#{_anchor(t.name)}) *(hidden)* | `{t.provenance.value}` | {_esc(t.desc)} |\n")
    out.append("\n")

    for t in public + hidden:
        out.append(f"### {t.name}\n\n")
        out.append(f"{_esc(t.desc)}\n\n")
        out.append(f"- **Provenance:** `{t.provenance.value}`\n")
        out.append(f"- **Primary key:** {', '.join(f'`{k}`' for k in t.pk)}\n")
        if t.fks:
            fks = "; ".join(f"`{c}` → `{o}.{oc}`" for c, o, oc in t.fks)
            out.append(f"- **Foreign keys:** {fks}\n")
        else:
            out.append("- **Foreign keys:** none\n")
        if t.hidden:
            out.append("- **Hidden:** yes. Ground truth, stored in `data/ground_truth/` only.\n")
        out.append("\n| Column | Type | Unit | Nullable | Description | Constraints |\n|---|---|---|---|---|---|\n")
        for c in t.cols:
            cons = []
            if c.nonneg:
                cons.append("≥ 0")
            if c.allowed:
                cons.append("one of " + ", ".join(f"`{a}`" for a in c.allowed))
            pk = " (PK)" if c.name in t.pk else ""
            out.append(
                f"| `{c.name}`{pk} | {c.dtype} | {_esc(c.unit)} | {'yes' if c.nullable else 'no'} | "
                f"{_esc(c.desc)} | {_esc('; '.join(cons))} |\n"
            )
        out.append("\n")
    return "".join(out)


def render_register() -> str:
    df = assumption_register()
    out = [HEADER.format(src="config/assumptions.yaml"), "# Assumption register\n\n"]
    out.append(
        "Every configurable parameter in [`config/assumptions.yaml`](../config/assumptions.yaml), "
        "flattened to one row per key. Provenance tags: **REAL** (public, cited dataset), "
        "**DERIVED** (computed in this repo), **ASSUMED** (a planning assumption chosen by the author), "
        "**SIMULATED** (produced by the synthetic generator). None of these values is measured "
        "aviation reliability or any operator's data.\n\n"
    )
    counts = df["provenance"].value_counts().to_dict()
    out.append("| Provenance | Keys |\n|---|---|\n")
    for p in schemas.PROVENANCE_VALUES:
        out.append(f"| {p} | {counts.get(p, 0)} |\n")
    out.append("\n")

    df = df.assign(section=df["key"].str.split(".").str[0])
    for section, grp in df.groupby("section", sort=False):
        out.append(f"## {section}\n\n")
        rats = [r for r in grp["rationale"].dropna().unique() if r]
        if rats:
            for r in rats:
                out.append(f"> {_esc(r)}\n\n")
        out.append("| Key | Value | Provenance |\n|---|---|---|\n")
        for _, row in grp.iterrows():
            val = row["value"]
            try:
                parsed = json.loads(val)
                val = parsed if isinstance(parsed, str) else val
            except (TypeError, ValueError):
                pass
            out.append(f"| `{row['key']}` | {_esc(val)} | {row['provenance']} |\n")
        out.append("\n")
    return "".join(out)


def main() -> None:
    DICT_OUT.parent.mkdir(parents=True, exist_ok=True)
    REG_OUT.parent.mkdir(parents=True, exist_ok=True)
    DICT_OUT.write_text(relabel(render_dictionary()), encoding="utf-8")
    REG_OUT.write_text(relabel(render_register()), encoding="utf-8")
    print(f"wrote {DICT_OUT.relative_to(ROOT)} ({len(schemas.TABLES)} tables)")
    print(f"wrote {REG_OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
